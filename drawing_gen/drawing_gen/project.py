"""
Three-view orthographic projection with hidden-line removal (OpenCascade HLR).

Conventions (verified empirically in test_drawings.py):
  N = direction TOWARD the viewer; in-view axes: X = Vx, Y = N x Vx; projected edges are 2D (z = 0).
  front: N=-y, Vx=+x   -> (x, z)        top: N=+z, Vx=+x -> (x, y)        right: N=+x, Vx=+y -> (y, z)
Primitives (all in view units = model mm):
  {"t":"line","p":[x0,y0,x1,y1]}  {"t":"circle","c":[x,y],"r":r}  {"t":"arc","c":[x,y],"r":r,"a0":deg,"a1":deg}  (arc is CCW a0->a1)
  {"t":"poly","pts":[[x,y],...]} for anything else (rare in axis-aligned views; sampled).
Only sharp and outline edges are produced. Smooth (tangent) edges are skipped, so fillets are not generated by parts.py.
"""
from __future__ import annotations

import math

import numpy as np
from OCP.BRepAdaptor import BRepAdaptor_Curve
from OCP.GeomAbs import GeomAbs_Circle, GeomAbs_Line
from OCP.gp import gp_Ax2, gp_Dir, gp_Pnt
from OCP.HLRAlgo import HLRAlgo_Projector
from OCP.HLRBRep import HLRBRep_Algo, HLRBRep_HLRToShape
from OCP.TopAbs import TopAbs_EDGE
from OCP.TopExp import TopExp_Explorer
from OCP.TopoDS import TopoDS
from shapely.geometry import LineString
from shapely.ops import unary_union

VIEWS = {"front": ((0, -1, 0), (1, 0, 0)), "top": ((0, 0, 1), (1, 0, 0)), "right": ((1, 0, 0), (0, 1, 0))}


def _as_line(pts: np.ndarray, tol: float = 1e-3):
    """A circle seen edge-on (or any degenerate curve) projects to a straight segment: return it as ONE line."""
    c = pts.mean(0)
    _, _, vt = np.linalg.svd(pts - c)
    d = vt[0]
    if np.abs((pts - c) @ vt[1]).max() > tol:
        return None
    t = (pts - c) @ d
    a, b = c + d * t.min(), c + d * t.max()
    if np.hypot(*(b - a)) < 1e-6:
        return None
    return {"t": "line", "p": [float(a[0]), float(a[1]), float(b[0]), float(b[1])]}


def _edges(comp) -> list:
    out = []
    if comp is None or comp.IsNull():
        return out
    ex = TopExp_Explorer(comp, TopAbs_EDGE)
    while ex.More():
        c = BRepAdaptor_Curve(TopoDS.Edge_s(ex.Current()))
        u0, u1 = c.FirstParameter(), c.LastParameter()
        p0, p1, pm = c.Value(u0), c.Value(u1), c.Value((u0 + u1) / 2)
        t = c.GetType()
        if t == GeomAbs_Line:
            if math.hypot(p1.X() - p0.X(), p1.Y() - p0.Y()) > 1e-6:
                out.append({"t": "line", "p": [p0.X(), p0.Y(), p1.X(), p1.Y()]})
        elif t == GeomAbs_Circle:
            circ = c.Circle()
            cx, cy, r = circ.Location().X(), circ.Location().Y(), circ.Radius()
            if abs((u1 - u0) - 2 * math.pi) < 1e-6:
                out.append({"t": "circle", "c": [cx, cy], "r": r})
            else:
                a0 = math.atan2(p0.Y() - cy, p0.X() - cx)
                a1 = math.atan2(p1.Y() - cy, p1.X() - cx)
                am = math.atan2(pm.Y() - cy, pm.X() - cx)
                sweep, msweep = (a1 - a0) % (2 * math.pi), (am - a0) % (2 * math.pi)
                if msweep > sweep:                    # mid point is on the other side: swap to keep CCW
                    a0, a1 = a1, a0
                out.append({"t": "arc", "c": [cx, cy], "r": r, "a0": math.degrees(a0) % 360, "a1": math.degrees(a1) % 360})
        else:
            pts = np.array([(c.Value(u0 + (u1 - u0) * k / 24).X(), c.Value(u0 + (u1 - u0) * k / 24).Y()) for k in range(25)])
            line = _as_line(pts)
            out.append(line if line else {"t": "poly", "pts": pts.tolist()})
        ex.Next()
    return out


def sample(p: dict, step: float = 0.5) -> np.ndarray:
    """Points along a primitive, spacing <= step."""
    if p["t"] == "line":
        x0, y0, x1, y1 = p["p"]
        n = max(2, int(math.hypot(x1 - x0, y1 - y0) / step) + 1)
        s = np.linspace(0, 1, n)
        return np.c_[x0 + (x1 - x0) * s, y0 + (y1 - y0) * s]
    if p["t"] in ("circle", "arc"):
        cx, cy = p["c"]
        r = p["r"]
        if p["t"] == "circle":
            a = np.linspace(0, 2 * math.pi, max(8, int(2 * math.pi * r / step)), endpoint=False)
        else:
            a0 = math.radians(p["a0"])
            sweep = (math.radians(p["a1"]) - a0) % (2 * math.pi)
            a = a0 + np.linspace(0, sweep, max(3, int(sweep * r / step) + 1))
        return np.c_[cx + r * np.cos(a), cy + r * np.sin(a)]
    pts = np.asarray(p["pts"], float)
    return pts


def _geom(p: dict, n: int = 128):
    return LineString(sample(p, 0.25) if p["t"] != "line" else sample(p, 1e9))


def _dedupe(prims: list, nd: int = 3) -> list:
    seen, out = set(), []
    for p in prims:
        if p["t"] == "line":
            a, b = tuple(round(v, nd) for v in p["p"][:2]), tuple(round(v, nd) for v in p["p"][2:])
            key = ("l",) + tuple(sorted([a, b]))
        elif p["t"] == "circle":
            key = ("c",) + tuple(round(v, nd) for v in p["c"]) + (round(p["r"], nd),)
        elif p["t"] == "arc":
            key = ("a",) + tuple(round(v, nd) for v in p["c"]) + (round(p["r"], nd), round(p["a0"], 1), round(p["a1"], 1))
        else:
            key = ("p", len(p["pts"]), round(p["pts"][0][0], nd), round(p["pts"][0][1], nd))
        if key not in seen:
            seen.add(key)
            out.append(p)
    return out


def suppress_hidden(visible: list, hidden: list, tol: float = 1e-3) -> list:
    """Drawing practice: a visible line takes priority over a coincident hidden line. Lines are trimmed
    to the uncovered pieces; arcs/circles are dropped when >=90% of their length is covered."""
    if not visible:
        return hidden
    cover = unary_union([_geom(p) for p in visible]).buffer(tol)
    out = []
    for h in hidden:
        g = _geom(h)
        rest = g.difference(cover)
        if rest.is_empty:
            continue
        if h["t"] == "line":
            parts = [rest] if rest.geom_type == "LineString" else list(getattr(rest, "geoms", []))
            for s in parts:
                if s.geom_type == "LineString" and s.length > 1e-3:
                    (x0, y0), (x1, y1) = s.coords[0], s.coords[-1]
                    out.append({"t": "line", "p": [x0, y0, x1, y1]})
        elif rest.length > 0.1 * g.length:
            out.append(h)
    return out


def project_view(shape, view: str) -> dict:
    """shape: cq.Shape. Returns {"visible": [...], "hidden": [...]} in model mm."""
    N, Vx = VIEWS[view]
    algo = HLRBRep_Algo()
    algo.Add(shape.wrapped)
    algo.Projector(HLRAlgo_Projector(gp_Ax2(gp_Pnt(0, 0, 0), gp_Dir(*N), gp_Dir(*Vx))))
    algo.Update()
    algo.Hide()
    h = HLRBRep_HLRToShape(algo)
    vis = _dedupe(_edges(h.VCompound()) + _edges(h.OutLineVCompound()))
    hid = _dedupe(_edges(h.HCompound()) + _edges(h.OutLineHCompound()))
    return {"visible": vis, "hidden": suppress_hidden(vis, hid)}


def bbox(prims: list) -> tuple:
    pts = np.vstack([sample(p, 1.0) for p in prims])
    return float(pts[:, 0].min()), float(pts[:, 1].min()), float(pts[:, 0].max()), float(pts[:, 1].max())
